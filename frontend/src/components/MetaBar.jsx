import { Coins, Cpu, Database, KeyRound, Shuffle, Timer, Zap } from "lucide-react";
import { cx } from "./ui/primitives";
import { formatInt } from "../lib/format";

function Chip({ icon: Icon, tone = "neutral", title, children }) {
  const tones = {
    neutral: "border-line bg-panel text-fg-muted",
    live: "border-accent/20 bg-accent-soft text-accent",
    cache: "border-cache/20 bg-cache-soft text-cache",
    warn: "border-warn/25 bg-warn-soft text-warn",
  };
  return (
    <span
      title={title}
      className={cx(
        "inline-flex h-6 items-center gap-1.5 rounded-md border px-2 font-mono text-[11px] leading-none whitespace-nowrap",
        tones[tone],
      )}
    >
      {Icon && <Icon className="size-3 shrink-0" strokeWidth={2.2} aria-hidden="true" />}
      {children}
    </span>
  );
}

/**
 * Per-request metadata for one assistant reply.
 * Each data-testid element contains exactly the contract value (labels live in sibling spans).
 */
export function MetaBar({ metadata }) {
  const isCache = metadata.resolution_source === "LLM_CACHE";
  const failed = metadata.failed_attempts ?? [];
  const failoverTitle = failed.length
    ? `Failed before success: ${failed.map((f) => `${f.key_id}${f.status ? ` → ${f.status}` : ""}`).join(", ")}`
    : undefined;

  return (
    <div className="flex flex-wrap items-center gap-1.5" aria-label="Response metadata">
      <Chip
        icon={isCache ? Database : Zap}
        tone={isCache ? "cache" : "live"}
        title={isCache ? "Served from LiteLLM response cache" : "Generated by a live model call"}
      >
        <span data-testid="meta-source">{metadata.resolution_source}</span>
      </Chip>

      <Chip icon={Cpu} title="Model that produced this reply">
        <span data-testid="meta-model" className="max-w-[16rem] truncate">
          {metadata.model}
        </span>
      </Chip>

      <Chip icon={Timer} title="Server-measured latency for this request">
        <span data-testid="meta-latency">{`${metadata.latency_ms} ms`}</span>
      </Chip>

      <Chip icon={Coins} title="Tokens for this request only — input: system + history + new message; output: this reply">
        <span className="text-fg-faint">in</span>
        <span data-testid="meta-input-tokens">{metadata.input_tokens}</span>
        <span className="text-fg-faint/60" aria-hidden="true">
          ·
        </span>
        <span className="text-fg-faint">out</span>
        <span data-testid="meta-output-tokens">{metadata.output_tokens}</span>
      </Chip>

      {metadata.key_id && (
        <Chip icon={KeyRound} title="API key from the pool that answered">
          <span data-testid="meta-key-id">{metadata.key_id}</span>
        </Chip>
      )}

      {metadata.fallback_attempts > 0 && (
        <Chip icon={Shuffle} tone="warn" title={failoverTitle}>
          <span data-testid="meta-fallback-attempts">
            {formatInt(metadata.fallback_attempts)} failover{metadata.fallback_attempts === 1 ? "" : "s"}
          </span>
        </Chip>
      )}

      {metadata.usage_estimated && (
        <Chip title="Provider did not report usage; tokens estimated with the model tokenizer">est.</Chip>
      )}
    </div>
  );
}
